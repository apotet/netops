export function getQuestionDeepDive(question: Question): QuestionDeepDive {
  const category = detectCategory(question);
  const correctText = question.correct.map((idx) => question.answers[idx]).join('; ');
  const historical = PREVIOUS_DIAGNOSTIC_QUESTIONS[question.id]?.text === question.text;
  const individual: (typeof INDIVIDUAL_DEEP)[string] | undefined = historical ? HISTORICAL_DIAGNOSTIC_DEEP[question.id] : INDIVIDUAL_DEEP[question.id] ?? explainGeneratedMask(question.id);
  const diagnostic = historical ? undefined : DIAGNOSTIC_EXPLANATIONS[question.id];
  const ipv4Prefix = ipv4CalculationPrefix(question.id);
  const audited = historical ? undefined : AUDITED_QUESTION_EXPLANATIONS[question.id];
  const baseExpl = audited?.brief ?? explanationText(question.explanation) ?? '';

  const briefAnswer =
    audited?.brief || individual?.brief ||
    (baseExpl.length > 0
      ? baseExpl
      : 'Индивидуальное объяснение в сохранённом вопросе отсутствует.');

  const deepAnalysis = audited?.deep ?? (individual
    ? individual.plain ?? individual.deep
    : diagnostic ? baseExpl : enrichExplanation(question, category, baseExpl));

  const engineeringDeep = audited?.deep ?? (
    question.difficulty === 'advanced' || question.difficulty === 'applied'
      ? (individual ? deepAnalysis : undefined) || (baseExpl.length > 80 ? baseExpl : undefined)
      : (individual ? deepAnalysis : undefined));

  // The existing theory/review toggle consumes professional. Layered entries
  // change only the detailed text; their brief and trap stay the same in both modes.
  const professional = individual?.pro
    ? {
        ...individual.professional,
        brief: individual.brief,
        deep: individual.pro,
        trap: individual.trap,
        // Historical gap-pack wording has a source revision; newly authored
        // plain/pro entries must not inherit that unrelated provenance.
        sourceCommit: individual.professional?.sourceCommit ??
          (/^gap-pack[123]-/.test(question.id) ? GAP_PACK_PRO_SOURCE_COMMIT : undefined),
      }
    : individual?.professional ?? diagnostic;

  const resolved: QuestionDeepDive = {
    questionId: question.id,
    category,
    categoryLabel: question.topic,
    categoryColor: getCategoryColor(category),
    briefAnswer,
    coreConcept: `Правильный ответ: «${correctText}». Тема: ${question.topic}.`,
    deepAnalysis,
    ...(individual?.plain !== undefined ? { plain: individual.plain } : {}),
    ...(individual?.pro !== undefined ? { pro: individual.pro } : {}),
    engineeringDeep,
    professional,
    practiceLink: individual?.practiceLink,
    hasIndividualDeep: Boolean(individual || diagnostic || audited?.deep),
    glossaryInProfessional: individual?.glossaryInProfessional ?? Boolean(diagnostic),
    commonTrap: audited?.trap ?? (individual?.trap || detectCommonTrap(question)),
    practicalTip: audited?.practicalTip ?? (question.remember || (BASE_FOUNDATIONS_BATCH7[question.id]?.practicalTip ?? (BASE_FOUNDATIONS_BATCH6[question.id]?.practicalTip ?? (BASE_FOUNDATIONS_BATCH5[question.id]
      ? 'Для медной линии сверяйте видимую маркировку и конструкцию с документацией; после оконцевания проверяйте wiremap, а категорию канала — измерениями.'
      : getPracticalTip(category))))),
    memorizationRule: question.remember,
    visualDiagram: generateDiagramForQuestion(question),
    ipv4Practice: ipv4Prefix === undefined ? undefined : {
      enabled: true,
      reason: 'Вопрос опирается на расчёт маски или границ подсети.',
      targetPrefix: ipv4Prefix,
      targetMode: 'calc',
    },
    ipv6Practice: question.id === 'l3-d06' ? { targetMode: 'type' }
      : individual?.ipv6Practice ? { targetMode: 'concept' } : undefined,
    keyTakeaways: generateKeyTakeaways(question, correctText, ipv4Prefix !== undefined),
    nextStudy: individual?.next,
  };
  // Historical diagnostic snapshots retain their original authored interpretation.
  return historical ? resolved : applyInDepthExplanation(question.id, resolved, question);
}

function detectCategory(q: Question): QuestionDeepDive['category'] {
  if (q.group === 'visual-l1') return 'visual';
  if (q.group === 'troubleshooting' || q.topic.includes('Диагностика')) return 'cli';
  if (q.group === 'tcpip' || q.topic.includes('TCP/IP') || q.topic.includes('Инкапсуляция')) return 'tcpip';
  if (q.group === 'l4' || q.topic.includes('L4') || q.topic.includes('TCP') || q.topic.includes('UDP')) return 'l4';
  if (
    q.group === 'l5-l7' ||
    q.topic.includes('L5') ||
    q.topic.includes('L7') ||
    q.topic.includes('DNS') ||
    q.topic.includes('DHCP') ||
    q.topic.includes('HTTP')
  )
    return 'l5_l7';
  if (
    q.group === 'l3' ||
    q.topic.includes('L3') ||
    q.topic.includes('IPv4') ||
    q.topic.includes('Маски') ||
    q.topic.includes('Подсети')
  )
    return 'l3';
  if (q.group === 'l1-l2') {
    if (q.topic.includes('L1') || q.topic.includes('Оптика') || q.topic.includes('Физический')) return 'l1';
    return 'l2';
  }
  return 'l3';
}

